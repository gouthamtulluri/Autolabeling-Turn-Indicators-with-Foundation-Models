def expand_mask_vertical(mask_array, expansion_ratio):
    """
    Expands a binary mask upward and downward only (width unchanged).
    
    Args:
        mask_array (np.ndarray): A 2D binary array representing the mask.
        expansion_ratio (float): Fraction of the mask's bounding-box height to add top and bottom.
        
    Returns:
        np.ndarray: A uint8 mask of the same shape with the vertical expansion applied.
    """

    if expansion_ratio <= 0:
        return (mask_array > 0).astype(np.uint8)
        
    mask_u8 = (mask_array > 0).astype(np.uint8)
    y_idx, _ = np.where(mask_u8 > 0)
    
    if len(y_idx) == 0:
        return mask_u8
        
    h = int(y_idx.max() - y_idx.min())
    k_size = max(1, int(h * expansion_ratio))
    
    # Kernel size must be odd for symmetric morphological dilation
    k_size = k_size if k_size % 2 == 1 else k_size + 1
    
    if k_size < 3:
        return mask_u8
        
    kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (1, k_size))
    return cv2.dilate(mask_u8, kernel, iterations=1)


def extract_cielab_amber_metrics(image_rgb, mask_array,
                                  ideal_l, ideal_a, ideal_b,
                                  max_dist, b_min):
    """
    Counts amber pixels inside a mask using a CIELAB sphere and b* floor threshold.
    
    Args:
        image_rgb (np.ndarray): The source RGB image array.
        mask_array (np.ndarray): The 2D binary mask denoting the region to check.
        ideal_l (float): Target L* value for the amber color.
        ideal_a (float): Target a* value for the amber color.
        ideal_b (float): Target b* value for the amber color.
        max_dist (float): Maximum 3D Euclidean distance in LAB space to be considered amber.
        b_min (float): Minimum b* (yellowness) floor to eliminate false positives.

    Returns:
        tuple: (amber_pct, amber_count, total_px)
            - amber_pct (float): Amber pixels as % of total mask pixels [primary blink signal].
            - amber_count (int): Raw amber pixel count [diagnostic].
            - total_px (int): Total non-black mask pixels [diagnostic / denominator].
    """

    valid_pixels = image_rgb[mask_array > 0]
    non_black    = np.any(valid_pixels > 0, axis=1)
    valid_pixels = valid_pixels[non_black]
    total_px     = len(valid_pixels)

    if total_px == 0:
        return (0.0, 0, 0)

    lab    = cv2.cvtColor(valid_pixels.reshape(-1, 1, 3),
                          cv2.COLOR_RGB2LAB).reshape(-1, 3)
    L_vals = lab[:, 0].astype(float)
    a_vals = lab[:, 1].astype(float)
    b_vals = lab[:, 2].astype(float)

    # Plain 3D Euclidean distance in LAB space
    dist = np.sqrt(
        (L_vals - ideal_l) ** 2 +
        (a_vals - ideal_a) ** 2 +
        (b_vals - ideal_b) ** 2
    )

    amber_mask  = (dist < max_dist) & (b_vals >= b_min)
    amber_count = int(amber_mask.sum())
    amber_pct   = amber_count / total_px * 100.0

    return (amber_pct, amber_count, total_px)


def associate_masks_to_boxes(
    df_2d_boxes, 
    masks_tensor,
    scores_tensor,
    is_rear_flags,      
    pixel_counts, 
    centroids_3d, 
    min_mask_area=20, 
    num_generated=0,
    num_valid=0
):
    """
    Associates 2D segmentation masks with 3D/2D vehicle bounding boxes.
    
    This function uses a hybrid approach, matching masks via 2D bounding polygon
    intersection and resolving ties or ambiguities using 3D spatial distancing.
    
    Args:
        df_2d_boxes (pd.DataFrame): Frame-level bounding box and 3D pose data for vehicles.
        masks_tensor (torch.Tensor): PyTorch tensor containing the generated masks.
        scores_tensor (torch.Tensor): PyTorch tensor containing confidence scores for masks.
        is_rear_flags (list of bool): Flags indicating if each mask targets the rear of a vehicle.
        pixel_counts (list of int): Total non-black pixels per mask (cheap, no color overhead).
        centroids_3d (list): The computed 3D centroids for each mask (if depth is available).
        min_mask_area (int): Minimum pixel area for a mask to be considered valid.
        num_generated (int): Total number of masks initially generated by the model.
        num_valid (int): Number of masks that passed the minimum area threshold.
        
    Returns:
        pd.DataFrame: A new dataframe containing updated indicator columns with the matched masks.
    """
    
    # Set up image dimensions and device
    if len(masks_tensor) > 0:
        device = masks_tensor.device
        img_h, img_w = masks_tensor.shape[1], masks_tensor.shape[2]
    else:
        device = "cpu"
        img_h, img_w = 1080, 1920
        
    track_wins = {row['track_id']: [] for _, row in df_2d_boxes.iterrows()}

    # Precompute Car Face Masks and Push to GPU
    cars = []
    for _, row in df_2d_boxes.iterrows():
        cam_name = row['camera']
        track_id = int(row['track_id'])
        yaw_val = row.get('yaw_3d', None)
            
        w, h = row.get('box_width', 0), row.get('box_height', 0)
        box_area = w * h
        car = {
            'track_id': track_id,
            'row': row,
            'cam_name': cam_name,
            'yaw_3d': yaw_val,
            'box_area': box_area
        }
        
        # Prepare CPU masks for intersection logic
        cx, cy = row['center_x'], row['center_y']
        w, h = row.get('box_width', 0), row.get('box_height', 0)
        xmin, ymin = int(cx - (w / 2)), int(cy - (h / 2))
        xmax, ymax = int(cx + (w / 2)), int(cy + (h / 2))
        
        for f_type in ['front', 'rear']:
            c_str = row.get(f"{f_type}_corners_2d", None)
            valid = False
            mask_np = np.zeros((img_h, img_w), dtype=np.uint8)
            
            if type(c_str) != float and c_str is not None:
                try:
                    import ast
                    pts = np.array(ast.literal_eval(c_str)) if isinstance(c_str, str) else np.array(c_str)
                    if len(pts) > 0:
                        hull = cv2.convexHull(pts.astype(np.int32))
                        cv2.fillPoly(mask_np, [hull], 1)
                        valid = True
                except:
                    pass
            
            # Fallback to standard rectangular bounding box if corner points fail
            if not valid:
                cv2.rectangle(mask_np, (max(0, xmin), max(0, ymin)), (min(img_w, xmax), min(img_h, ymax)), 1, -1)
                
            import torch
            car[f"{f_type}_mask_tensor"] = torch.from_numpy(mask_np).to(device=device, dtype=torch.bool)
            
        cars.append(car)

    # Assign Masks to Candidate Boxes
    for i in range(len(masks_tensor)):
        mask = masks_tensor[i]
        score = scores_tensor[i].item()
        is_rear = is_rear_flags[i]
        
        total_mask_pixels = pixel_counts[i]
        if total_mask_pixels < min_mask_area:
            continue
            
        # Centroid extraction
        y_coords, x_coords = torch.where(mask > 0)
        if len(x_coords) == 0: continue
        mask_cx = x_coords.float().mean().item()
        mask_cy = y_coords.float().mean().item()
            
        m3d = centroids_3d[i]
        candidates_2d = []
        candidates_3d = []
        box_padding = 0.2
        
        for car in cars:
            face_mask = car['rear_mask_tensor'] if is_rear else car['front_mask_tensor']
            pixels_in_box = torch.sum((mask > 0) & face_mask).item()
            
            if pixels_in_box > 0:
                candidates_2d.append({'car': car, 'containment': 0, 'pixels_in_box': pixels_in_box})
                    
            if m3d is not None:
                row = car['row']
                V_x, V_y = row['x_3d'], row['y_3d']
                yaw_val = row['yaw_3d'] if not pd.isna(row['yaw_3d']) else 0.0
                W = row.get('width_3d', 2.0)
                L = row.get('length_3d', 5.0)
                dx = m3d[0] - V_x
                dy = m3d[1] - V_y
                l_x = np.cos(yaw_val)*dx + np.sin(yaw_val)*dy
                l_y = -np.sin(yaw_val)*dx + np.cos(yaw_val)*dy
                
                # Check if the mask's 3D projection lands within the vehicle bounds
                if abs(l_x) <= (W/2 + box_padding) and abs(l_y) <= (L/2 + box_padding):
                    candidates_3d.append({'car': car, 'l_x': l_x, 'l_y': l_y})
                 
        # 3D - 2D Hybrid Resolution Logic
        ids_2d = [c['car']['track_id'] for c in candidates_2d]
        ids_3d = [c['car']['track_id'] for c in candidates_3d]
        unique_track_ids = set(ids_2d + ids_3d)
        num_candidates = len(unique_track_ids)
        
        winner_car = None
        state_tag = 2
        is_left_vehicle = False

        if num_candidates == 1:
            track_id = list(unique_track_ids)[0]
            if track_id in ids_3d:
                state_tag = 1
                c3d = next(c for c in candidates_3d if c['car']['track_id'] == track_id)
                winner_car = c3d['car']
                is_left_vehicle = c3d['l_y'] > 0
            else:
                state_tag = 0
                c2d = next(c for c in candidates_2d if c['car']['track_id'] == track_id)
                winner_car = c2d['car']
                
                # 2D assignment resolution based on bounding box geometry
                row = winner_car['row']
                c_str = row.get("rear_corners_2d" if is_rear else "front_corners_2d", None)
                valid_corners = False
                vehicle_left_cx, vehicle_right_cx = None, None
                
                if type(c_str) != float and c_str is not None:
                    try:
                        pts = np.array(ast.literal_eval(c_str)) if isinstance(c_str, str) else np.array(c_str)
                        if len(pts) == 4:
                            if is_rear:
                                vehicle_right_cx, vehicle_left_cx = (pts[0][0] + pts[2][0])/2, (pts[1][0] + pts[3][0])/2
                            else:
                                vehicle_left_cx, vehicle_right_cx = (pts[0][0] + pts[2][0])/2, (pts[1][0] + pts[3][0])/2
                            valid_corners = True
                    except: pass
                    
                if valid_corners:
                    is_left_vehicle = abs(mask_cx - vehicle_left_cx) < abs(mask_cx - vehicle_right_cx)
                else:
                    face_cx = row.get('rear_cx' if is_rear else 'front_cx', row['center_x'])
                    is_on_left_screen = mask_cx < face_cx
                    is_left_vehicle = (is_on_left_screen and is_rear) or (not is_on_left_screen and not is_rear)
                    
        elif num_candidates > 1:
            # Multi-candidate conflict resolution relying strictly on precise 3D placement
            if len(candidates_3d) == 1:
                winner = candidates_3d[0]
                winner_car = winner['car']
                state_tag = 1
                is_left_vehicle = winner['l_y'] > 0

        # Append winning candidate to track register
        if winner_car is not None:
            track_wins[winner_car['track_id']].append({
                'mask_idx': i,
                'score': score, 
                'mask_cx': mask_cx, 'mask_cy': mask_cy,
                'mask_cx_3d': m3d[0] if m3d is not None else None,
                'mask_cy_3d': m3d[1] if m3d is not None else None,
                'area': total_mask_pixels,
                'is_rear': is_rear, 'yaw_3d': winner_car['yaw_3d'],
                'cam_name': winner_car['cam_name'],
                'state_tag': state_tag,
                'is_left_vehicle': is_left_vehicle
            })

    # Geometric Left/Right Classification
    updated_rows = []
    for _, row in df_2d_boxes.iterrows():
        row_dict = row.to_dict()
        track_id = int(row['track_id'])
        claimed_masks = track_wins[track_id]
        
        row_dict['frame_generated_masks'] = num_generated
        row_dict['frame_valid_masks'] = num_valid
        
        row_dict['rear_left_indicator'] = None
        row_dict['rear_right_indicator'] = None
        row_dict['front_left_indicator'] = None
        row_dict['front_right_indicator'] = None
        row_dict['associated_masks'] = "[]"
        
        if claimed_masks:
            # Sort masks by SAM Score (Descending) to prioritize the best segmentation
            claimed_masks = sorted(claimed_masks, key=lambda x: x['score'], reverse=True)
            
            for m in claimed_masks:
                is_rear_target = m['is_rear'] 
                
                if m['state_tag'] == 1:
                    is_left_vehicle = m['is_left_vehicle']
                else:
                    c_str = row.get("rear_corners_2d" if is_rear_target else "front_corners_2d", None)
                    valid_corners = False
                    vehicle_left_cx, vehicle_right_cx = None, None

                    if type(c_str) != float and c_str is not None:
                        try:
                            pts = np.array(ast.literal_eval(c_str)) if isinstance(c_str, str) else np.array(c_str)
                            if len(pts) == 4:
                                # 3D Order mapping from transform.py:
                                if is_rear_target:
                                    vehicle_right_cx = (pts[0][0] + pts[2][0]) / 2.0
                                    vehicle_left_cx  = (pts[1][0] + pts[3][0]) / 2.0
                                else:
                                    vehicle_left_cx  = (pts[0][0] + pts[2][0]) / 2.0
                                    vehicle_right_cx = (pts[1][0] + pts[3][0]) / 2.0
                                valid_corners = True
                        except: pass

                    if valid_corners:
                        dist_to_vehicle_left = abs(m['mask_cx'] - vehicle_left_cx)
                        dist_to_vehicle_right = abs(m['mask_cx'] - vehicle_right_cx)
                        is_left_vehicle = dist_to_vehicle_left < dist_to_vehicle_right
                    else:
                        if is_rear_target and 'rear_cx' in row and not pd.isna(row['rear_cx']): face_cx = row['rear_cx']
                        elif not is_rear_target and 'front_cx' in row and not pd.isna(row['front_cx']): face_cx = row['front_cx']
                        else: face_cx = row['center_x']

                        is_on_left = m['mask_cx'] < face_cx
                        is_left_vehicle = (is_on_left and is_rear_target) or (not is_on_left and not is_rear_target)
                
                # Assign to 4 specific columns based on geometry
                if is_left_vehicle:
                    col_target = 'rear_left_indicator' if is_rear_target else 'front_left_indicator'
                else:
                    col_target = 'rear_right_indicator' if is_rear_target else 'front_right_indicator'

                if row_dict[col_target] is None:
                    row_dict[col_target] = str({
                        'mask_idx': m['mask_idx'],
                        'mask_cx': m['mask_cx'],
                        'mask_cy': m['mask_cy'],
                        'is_rear': is_rear_target,
                        'state_tag': m['state_tag'],
                        'cx_3d': m['mask_cx_3d'],
                        'cy_3d': m['mask_cy_3d']
                    })

            # Log data for all associated masks in a single column
            row_dict['associated_masks'] = str([
                {
                    'mask_idx': m['mask_idx'], 
                    'state_tag': m['state_tag'], 
                    'cx_3d': round(m['mask_cx_3d'], 2) if m['mask_cx_3d'] is not None else None,
                    'cy_3d': round(m['mask_cy_3d'], 2) if m['mask_cy_3d'] is not None else None,
                    'cx': m['mask_cx'], 
                    'cy': m['mask_cy'], 
                    'score': round(m['score'], 4),
                    'area': m['area']
                } for m in claimed_masks
            ])

        updated_rows.append(row_dict)

    return pd.DataFrame(updated_rows)


def process_all_valid_images_with_sam(
    camera_dataframes, 
    sync_table,     
    calib_data,
    data_root, 
    processor, 
    model, 
    device, 
    inference_targets=None,
    exclude_prompt=None,          
    sam_conf_threshold=0.50,      
    sam_mask_threshold=0.80,         
    min_mask_area=20,
    target_object_types=['Car', 'Van', 'Truck', 'Bus', 'Trailer', 'E-Scooter', 'Motorcycle'],
    save_csv=False,
    save_masks=False,
    depth_processor=None,
    depth_model=None,
    ideal_l=205,
    ideal_a=153,
    ideal_b=208,
    rear_max_dist=80,
    rear_b_min=135,
    rear_expansion=0.20,
    front_max_dist=80,
    front_b_min=135,
    front_expansion=0.10,
):
    """
    Master pipeline orchestrator for semantic mask generation, depth fusion, and association.
    
    Iterates through all valid vehicle timestamps across cameras, generates masks using SAM3,
    fuses LiDAR point clouds for dense depth estimation, and associates detected indicator 
    masks back to their respective vehicle tracks. Finally, it extracts CIELAB color metrics
    for the matched regions.
    
    Args:
        camera_dataframes (dict or pd.DataFrame): Track-wise or frame-wise vehicle detections.
        sync_table (dict): Lookup table to match master timestamps to camera image timestamps.
        calib_data (dict): Calibration parameters for camera undistortion and 3D projection.
        data_root (str): Root directory containing the raw image and LiDAR datasets.
        processor: The main SAM3 processor instance.
        model: The main SAM3 model instance.
        device: Hardware device to run the inference on.
        inference_targets (list of dict, optional): Targets to search for (e.g., headlights).
        exclude_prompt (str, optional): Text prompt to explicitly ignore during segmentation.
        sam_conf_threshold (float): Confidence threshold for SAM3 mask generation.
        sam_mask_threshold (float): Threshold for binarizing SAM3 outputs.
        min_mask_area (int): Minimum pixel area for valid masks.
        target_object_types (list of str): List of vehicle class names to process.
        save_csv (bool): If True, intermediate and final results are saved to disk.
        save_masks (bool): If True, generated masks are compressed and saved to disk.
        depth_processor: Processor for the dense depth estimation model.
        depth_model: Model for dense depth estimation.
        ideal_l (float): Target L* value for the indicator color.
        ideal_a (float): Target a* value for the indicator color.
        ideal_b (float): Target b* value for the indicator color.
        rear_max_dist (float): Max LAB space distance for rear indicators.
        rear_b_min (float): Min b* value for rear indicators.
        rear_expansion (float): Vertical expansion ratio for rear indicator masks.
        front_max_dist (float): Max LAB space distance for front indicators.
        front_b_min (float): Min b* value for front indicators.
        front_expansion (float): Vertical expansion ratio for front indicator masks.
        
    Returns:
        pd.DataFrame: A unified dataframe containing all tracked vehicles with 
                      matched indicator masks and their respective color metrics.
    """

    # Initialising Variables
    output_dir = "runs/result"
    dataset_name = os.path.basename(os.path.normpath(data_root)) or "dataset"
    checkpoint_interval = 200
    
    # Safely default to targets if none are provided
    if inference_targets is None:
        inference_targets = [
            {"text": "car taillight", "is_rear": True},
            {"text": "car headlight", "is_rear": False}
        ]

    print("="*60)
    print(f"Starting the pipeline....")
    print(f"Target Classes: {target_object_types}") 
    print(f"Segmentation Targets: {[t['text'] for t in inference_targets]}") 
    print("="*60)
    
    # Filter given dataset for target objects
    if isinstance(camera_dataframes, dict):
        valid_dfs = []
        for cam, df in camera_dataframes.items():
            if not df.empty:
                df_filtered = df[df['object_type'].isin(target_object_types)].copy()
                if not df_filtered.empty:
                    if 'camera' not in df_filtered.columns:
                        df_filtered['camera'] = cam
                    valid_dfs.append(df_filtered)
        if not valid_dfs: return pd.DataFrame()
        df_2d_boxes = pd.concat(valid_dfs, ignore_index=True)
    else:
        df_2d_boxes = camera_dataframes.copy()
        if not df_2d_boxes.empty and 'object_type' in df_2d_boxes.columns:
            df_2d_boxes = df_2d_boxes[df_2d_boxes['object_type'].isin(target_object_types)]

    if df_2d_boxes.empty: return pd.DataFrame()

    # Drop a row if valid image is not present in the folder
    def get_image_timestamp(row):
        try:
            ts_idx = sync_table['timestamp_nanoseconds'].index(row['timestamp'])
            return int(sync_table[row['camera']][ts_idx][0])
        except (ValueError, IndexError, KeyError):
            return None

    df_2d_boxes['image_associated_timestamp'] = df_2d_boxes.apply(get_image_timestamp, axis=1)
    df_2d_boxes = df_2d_boxes.dropna(subset=['image_associated_timestamp'])
    
    if df_2d_boxes.empty: return pd.DataFrame()
    df_2d_boxes['image_associated_timestamp'] = df_2d_boxes['image_associated_timestamp'].astype(int)

    # Image List Generation
    all_associations = []
    unique_images = df_2d_boxes[['camera', 'timestamp', 'image_associated_timestamp']].drop_duplicates()
    
    # Looping via unique images
    for index, row in tqdm(unique_images.iterrows(), total=len(unique_images), desc="Processing Images"):
        cam = row['camera']
        master_ts = row['timestamp']
        img_time = row['image_associated_timestamp'] 
        
        df_cars_in_image = df_2d_boxes[(df_2d_boxes['camera'] == cam) & (df_2d_boxes['timestamp'] == master_ts)]
        if df_cars_in_image.empty: 
            continue

        image_path = os.path.join(data_root, cam, f"{img_time}.jpg") 
        
        # Preserve track ids with blank stats if image is missing
        if not os.path.exists(image_path): 
            df_blank = associate_masks_to_boxes(df_cars_in_image, [], [], [], [], [])
            all_associations.append(df_blank)
            continue 
        
        raw_img = cv2.imread(image_path)
        
        # Preserve track ids with blank stats if image is corrupted
        if raw_img is None: 
            df_blank = associate_masks_to_boxes(df_cars_in_image, [], [], [], [], [])
            all_associations.append(df_blank)
            continue
            
        img_rgb = cv2.cvtColor(raw_img, cv2.COLOR_BGR2RGB)
        
        # Fisheye lens distorted image is flattened using native function from 'DrivIng'
        undistort_function = calib_data['cameras'][cam]['undistort_function']
        flat_img = undistort_function(img_rgb)
        pil_image = Image.fromarray(flat_img)

        
        # Step 1: generating 3d dense depth map using LiDAR pcd and Depth Anything 3
        lidar_path = os.path.join(data_root, "middle_lidar", f"{master_ts}.npz")
        valid_lidar = os.path.exists(lidar_path)

        K = None
        lTc = None
        dense_cam_z = None
        
        # Transforming lidar 3d data to 2d and running DA3
        if valid_lidar and depth_model is not None:
            
            img_h, img_w = flat_img.shape[:2]
            
            u_valid, v_valid, true_z, K, lTc = project_lidar_to_2d(
                lidar_path=lidar_path, 
                calib_data=calib_data, 
                camera_name=cam, 
                img_w=img_w, 
                img_h=img_h)
            
            dense_cam_z = get_dense_metric_depth(flat_img, u_valid, v_valid, true_z, depth_processor, depth_model, device)


        # Step 2: generating SAM3 masks for an image
        all_masks_tensors = []
        all_scores_tensors = []
        all_is_rear_flags = []
        
        for target in inference_targets:
            masks_t, scores_t = generate_sam3_masks(
                image_path=pil_image, 
                text_prompt=target["text"], 
                exclude_prompt=exclude_prompt,   
                processor=processor, model=model, device=device, 
                conf_threshold=sam_conf_threshold, mask_threshold=sam_mask_threshold
            )
            
            if len(masks_t) > 0:
                all_masks_tensors.append(masks_t)
                all_scores_tensors.append(scores_t)
                all_is_rear_flags.extend([target["is_rear"]] * len(masks_t))
                
        # Preserve cars with blank stats if SAM finds zero masks
        if len(all_masks_tensors) == 0:
            df_blank = associate_masks_to_boxes(df_cars_in_image, [], [], [], [], [])
            all_associations.append(df_blank)
            continue
            
        # Concat GPU Tensors
        master_masks_tensor = torch.cat(all_masks_tensors, dim=0)
        master_scores_tensor = torch.cat(all_scores_tensors, dim=0)

        
        # Step 3: logging pixel counts + 3D centroids
        mask_pixel_counts = []
        num_valid_masks = 0
        
        masks_cpu = master_masks_tensor.cpu().numpy()
        
        if save_masks == True:
            # Create exact requested structure: runs/masks_<dataset_name>/<camera_name>/
            mask_save_dir = os.path.join(output_dir, f"masks_{dataset_name}", cam)
            os.makedirs(mask_save_dir, exist_ok=True)
            
            # Dictionary comprehension to name each mask by its index
            mask_dict = {str(i): (m_np > 0) for i, m_np in enumerate(masks_cpu)}
            
            if mask_dict:
                # Save ALL masks into ONE highly compressed .npz archive named after the timestamp
                archive_path = os.path.join(mask_save_dir, f"{img_time}.npz")
                np.savez_compressed(archive_path, **mask_dict)
        
        mask_centroids_3d = []
        for m_np in masks_cpu:
            # Pixel count is free: just sum the boolean mask
            total_px = int(m_np.sum())
            mask_pixel_counts.append(total_px)
            
            if total_px < min_mask_area:
                mask_centroids_3d.append(None)
                continue
            
            num_valid_masks += 1
            
            median_3d = None
            if dense_cam_z is not None and K is not None and lTc is not None:
                y_indices, x_indices = np.where(m_np > 0)
                if len(x_indices) > 0:
                    cx_pixel = int(np.mean(x_indices))
                    cy_pixel = int(np.mean(y_indices))
                    mask_depths = dense_cam_z[m_np > 0]
                    if len(mask_depths) > 0:
                        median_cam_z = np.median(mask_depths)
                        X_c = (cx_pixel - K[0,2]) * median_cam_z / K[0,0]
                        Y_c = (cy_pixel - K[1,2]) * median_cam_z / K[1,1]
                        cam_point_3d = np.array([X_c, Y_c, median_cam_z, 1.0])
                        median_3d = (lTc @ cam_point_3d)[:3]

            mask_centroids_3d.append(median_3d)


        # Step 4: associating masks to track ids & classification to left-right
        df_verified = associate_masks_to_boxes(
            df_2d_boxes=df_cars_in_image, 
            masks_tensor=master_masks_tensor, 
            scores_tensor=master_scores_tensor,
            is_rear_flags=all_is_rear_flags,  
            pixel_counts=mask_pixel_counts, 
            centroids_3d=mask_centroids_3d,
            min_mask_area=min_mask_area,
            num_generated=len(master_masks_tensor),    
            num_valid=num_valid_masks    
        )


        # Step 5: vertical expansion + CIELAB amber % for assoicated-classified masks
        INDICATOR_COLS = ['rear_left_indicator', 'rear_right_indicator',
                           'front_left_indicator', 'front_right_indicator']

        # Collect {mask_idx: is_rear} for every assigned indicator slot
        winning = {}   # mask_idx -> is_rear (bool)
        for col in INDICATOR_COLS:
            if col not in df_verified.columns:
                continue
            col_is_rear = col.startswith('rear_')
            for val in df_verified[col].dropna():
                try:
                    winning[ast.literal_eval(str(val))['mask_idx']] = col_is_rear
                except: pass

        # Run vertical expansion + CIELAB filtering
        metrics_cache = {}
        for midx, is_rear in winning.items():
            if not (0 <= midx < len(masks_cpu)):
                continue
            exp   = rear_expansion if is_rear else front_expansion
            mdist = rear_max_dist  if is_rear else front_max_dist
            bmin  = rear_b_min     if is_rear else front_b_min

            exp_mask = expand_mask_vertical(masks_cpu[midx], exp)
            metrics_cache[midx] = extract_cielab_amber_metrics(
                flat_img, exp_mask,
                ideal_l, ideal_a, ideal_b,
                mdist, bmin
            )

        # Patch amber_pct / amber_count / total_px back into each column
        for col in INDICATOR_COLS:
            if col not in df_verified.columns:
                continue
            for idx, val in df_verified[col].items():
                if val is None or (isinstance(val, float) and pd.isna(val)):
                    continue
                try:
                    d = ast.literal_eval(str(val))
                    midx = d['mask_idx']
                    if midx in metrics_cache:
                        d['amber_pct'], d['amber_count'], d['total_px'] = metrics_cache[midx]
                        df_verified.at[idx, col] = str(d)
                except: pass

        if not df_verified.empty:
            all_associations.append(df_verified)

        
        # Intermediate csv outputs to prevent data loss in case of server failure
        if save_csv and len(all_associations) > 0 and len(all_associations) % checkpoint_interval == 0:
            os.makedirs(output_dir, exist_ok=True)
            chkpt_df = pd.concat([d.dropna(axis=1, how='all') for d in all_associations], ignore_index=True)
            chkpt_path = os.path.join(output_dir, f"SAM3_hybrid_checkpoint_{dataset_name}.csv")
            chkpt_df.to_csv(chkpt_path, index=False)
            tqdm.write(f"CHECKPOINT: Flushed {len(chkpt_df)} rows to {chkpt_path}")

    # Master DataFrame Stitching
    if all_associations:
        cleaned_associations = [df.dropna(axis=1, how='all') for df in all_associations]
        
        df_final_master = pd.concat(cleaned_associations, ignore_index=True)
        
        df_final_master = df_final_master.sort_values(by=['timestamp', 'camera', 'track_id']).reset_index(drop=True)
        
        if 'image_associated_timestamp' in df_final_master.columns:
            df_final_master = df_final_master.drop(columns=['image_associated_timestamp'])
        
        if save_csv:
            os.makedirs(output_dir, exist_ok=True)
            final_path = os.path.join(output_dir, f"SAM3_hybrid_final_{dataset_name}.csv")
            df_final_master.to_csv(final_path, index=False)
            print(f"FINAL SAVED: {final_path}")
            
        print("\n PIPELINE COMPLETE!")
        return df_final_master
    else:
        print("\n PIPELINE COMPLETE: No matches found.")
        return pd.DataFrame()