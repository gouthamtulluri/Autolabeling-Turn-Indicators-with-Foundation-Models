import cv2
import numpy as np
import warnings
import os
import pandas as pd

def extract_2d_boxes_from_annotations(annotations: list, vTl: np.ndarray, cTv: np.ndarray, K: np.ndarray, D: np.ndarray=None, img_w=1920, img_h=1080):
    if annotations is None or len(annotations) == 0:
        return []

    n_boxes = len(annotations)
    
    # 1. Box edges and Local corners template
    # Coordinates are [x, y, z, 1]. Y is the longitudinal (forward) direction.
    # Rear points (y = -0.5): indices 0, 3, 4, 7
    # Front points (y = 0.5): indices 1, 2, 5, 6
    corners = np.array([
        [-0.5, -0.5, -0.5, 1], [-0.5,  0.5, -0.5, 1],
        [ 0.5,  0.5, -0.5, 1], [ 0.5, -0.5, -0.5, 1],
        [-0.5, -0.5,  0.5, 1], [-0.5,  0.5,  0.5, 1],
        [ 0.5,  0.5,  0.5, 1], [ 0.5, -0.5,  0.5, 1]
    ], dtype=np.float64)

    all_corners = []
    meta_info = [] 
    
    for ann in annotations:
        pos = np.array(ann['position'], dtype=np.float64)
        dims = np.array(ann['dimension'], dtype=np.float64)  
        yaw = ann['orientation']

        c_scaled = corners.copy()
        c_scaled[:,0] *= dims[0]
        c_scaled[:,1] *= dims[1]
        c_scaled[:,2] *= dims[2]

        R = np.eye(4)
        R[:2,:2] = [[np.cos(yaw), -np.sin(yaw)],
                    [np.sin(yaw),  np.cos(yaw)]]

        T = np.eye(4)
        T[:3,3] = pos

        M = T @ R
        c_transformed = (M @ c_scaled.T).T  
        all_corners.append(c_transformed)
        meta_info.append({'track_id': ann['track_id'], 'object_type': ann['object_type'], 'x_3d': ann['position'][0], 'y_3d': ann['position'][1], 'z_3d': ann['position'][2], 'yaw_3d': yaw, 'width_3d': dims[0], 'length_3d': dims[1]})

    all_corners = np.vstack(all_corners)  

    # 2. Transform all boxes to camera frame
    cam_corners = (cTv @ vTl @ all_corners.T).T  
    cam_corners_reshaped = cam_corners.reshape(n_boxes, 8, 4)
    
    # Z-Culling
    z_positive = np.all(cam_corners_reshaped[:,:,2] > 0, axis=1)

    if not np.any(z_positive):
        return []

    cam_corners_reshaped = cam_corners_reshaped[z_positive]
    meta_info = [m for i, m in enumerate(meta_info) if z_positive[i]]
    n_valid = len(meta_info)

    pts_3d = cam_corners_reshaped[:,:,:3].reshape(-1,3).astype(np.float32)

    # 3. OpenCV Projection Routing
    if D is not None:
        if D.shape[0] == 5:  
            pts_2d, _ = cv2.projectPoints(
                pts_3d.reshape(-1,1,3), rvec=np.zeros(3), tvec=np.zeros(3), cameraMatrix=K, distCoeffs=D
            )
            pts_2d = pts_2d.reshape(-1,2)
        elif D.shape[0] == 4:  
            pts_2d, _ = cv2.fisheye.projectPoints(
                pts_3d.reshape(-1,1,3), rvec=np.zeros(3), tvec=np.zeros(3), K=K, D=D
            )
            pts_2d = pts_2d.reshape(-1,2)
    else:  
        proj = (K @ pts_3d.T).T
        pts_2d = proj[:,:2] / proj[:,2:3]

    # --- NATIVE MATH EXECUTION ---
    # Temporarily suppress the RuntimeWarning just for this specific native cast operation
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", category=RuntimeWarning)
        img_pts = np.round(pts_2d).astype(np.int32).reshape(n_valid,8,2)

    # 4. Extract to List
    extracted_boxes = []
    for i in range(n_valid):
        box = img_pts[i]
        
        # Native clipping logic catches the corrupted int32s generated by NaNs
        if np.all((box[:,0] < 0) | (box[:,0] >= img_w) |
                  (box[:,1] < 0) | (box[:,1] >= img_h)):
            continue

        x_min, y_min = np.min(box, axis=0)
        x_max, y_max = np.max(box, axis=0)

        # Clamp to image boundaries
        x_min, y_min = max(0, x_min), max(0, y_min)
        x_max, y_max = min(img_w, x_max), min(img_h, y_max)

        width = x_max - x_min
        length = y_max - y_min
        
        # NEW: Face extraction based on visual x-longitudinal logic
        rear_corners = box[[0, 1, 4, 5]]
        front_corners = box[[2, 3, 6, 7]]
        
        rear_cx = np.mean(rear_corners[:, 0])
        rear_cy = np.mean(rear_corners[:, 1])
        front_cx = np.mean(front_corners[:, 0])
        front_cy = np.mean(front_corners[:, 1])
        
        extracted_boxes.append({
            'track_id': meta_info[i]['track_id'],
            'object_type': meta_info[i]['object_type'],
            'center_x': x_min + (width / 2.0),
            'center_y': y_min + (length / 2.0),
            'x_3d': meta_info[i]['x_3d'],
            'y_3d': meta_info[i]['y_3d'],
            'z_3d': meta_info[i]['z_3d'],
            'yaw_3d': meta_info[i]['yaw_3d'],
            'width_3d': meta_info[i]['width_3d'],
            'length_3d': meta_info[i]['length_3d'],
            'box_width': width,
            'box_height': length,
            'rear_cx': rear_cx,
            'rear_cy': rear_cy,
            'front_cx': front_cx,
            'front_cy': front_cy,
            'rear_corners_2d': rear_corners.tolist(),
            'front_corners_2d': front_corners.tolist()
        })

    return extracted_boxes


def project_lidar_to_2d(lidar_path, calib_data, camera_name, img_w, img_h):
    """
    Loads sparse LiDAR point clouds, transforms them into the target camera's 
    coordinate space, and projects them onto the 2D image plane.
    
    Returns:
        u_valid, v_valid (np.ndarray): 2D pixel coordinates of valid LiDAR hits.
        true_z (np.ndarray): The physical depth (in meters) for each valid hit.
    """
    # 1. Load LiDAR points
    lidar_data = np.load(lidar_path)
    pts_raw = np.vstack([lidar_data['x'], lidar_data['y'], lidar_data['z']]).T
    pts_hom = np.hstack((pts_raw, np.ones((pts_raw.shape[0], 1))))
    
    # 2. Extract Calibration Matrices
    vTl = np.array(calib_data['lidars']['middle_lidar']['vTl'], dtype=np.float64)
    cam_calib = calib_data['cameras'][camera_name]
    cTv = np.array(cam_calib['cTv'], dtype=np.float64)
    K = np.array(cam_calib['K_undistortion'], dtype=np.float64)
    cTl = cTv @ vTl
    lTc = np.linalg.inv(cTl)
    
    
    # 3. Transform from Vehicle to Camera 3D space
    cam_points = (cTl @ pts_hom.T).T
    
    # Cull points behind the camera
    valid_z = cam_points[:, 2] > 0
    cam_points = cam_points[valid_z]
    
    # 4. Project to 2D Image Plane
    uv_points = (K @ cam_points[:, :3].T).T
    u = uv_points[:, 0] / uv_points[:, 2]
    v = uv_points[:, 1] / uv_points[:, 2]
    
    # 5. Filter bounds to fit inside the image dimensions
    valid_uv = (u >= 0) & (u < img_w) & (v >= 0) & (v < img_h)
    u_valid = u[valid_uv].astype(int)
    v_valid = v[valid_uv].astype(int)
    true_z = cam_points[valid_uv, 2]
    
    return u_valid, v_valid, true_z, K, lTc


def generate_camera_transform(target_camera, sync_table, calib_data, annots_time_wise):
    """
    Extracts 3D annotations and projects them into the 2D Pinhole (undistorted) 
    camera space, returning a formatted Pandas DataFrame with both master and camera timestamps.
    """
    df_rows = []
    cam_calib = calib_data['cameras'][target_camera]
    vTl = calib_data['lidars']['middle_lidar']['vTl']
    cTv = cam_calib['cTv']

    # Use the Undistorted Intrinsic Matrix and drop the Distortion array
    K_undistorted = cam_calib['K_undistortion']
    D_none = None 

    # ---> CHANGED: Added enumerate() to get the row index (ts_idx) instantly
    for ts_idx, ts in enumerate(sync_table['timestamp_nanoseconds']):
        if ts is None or ts not in annots_time_wise:
            continue
            
        # ---> NEW: Extract the actual camera timestamp using the sync table index
        try:
            cam_data = sync_table[target_camera][ts_idx]
            # Handles both flat lists and nested lists (like sync_table[cam][idx][0])
            # 1. Safely extract the raw value whether it's a list or a string
            raw_val = cam_data[0] if isinstance(cam_data, (list, tuple)) else cam_data
        
            # 2. Check for empty strings or None (The dropped frame failsafe)
            if not raw_val or str(raw_val).strip() == '':
                continue 
            
            # 3. Only convert to integer once we know we have actual data
            camera_ts = int(raw_val)
        except (IndexError, KeyError):
            continue  # Skip if the sync table is missing data for this frame
            
        annotations_in_frame = annots_time_wise[ts]
        
        # Run the math using the Pinhole model
        frame_boxes = extract_2d_boxes_from_annotations(
            annotations=annotations_in_frame, 
            vTl=vTl, 
            cTv=cTv, 
            K=K_undistorted, 
            D=D_none 
        )
        
        for box in frame_boxes:
            box['timestamp'] = ts                # The Universal/LiDAR Timestamp
            box['camera_timestamp'] = camera_ts  # The Actual Camera Shutter Timestamp
            df_rows.append(box)

    df_camera_boxes = pd.DataFrame(df_rows)
    
    if not df_camera_boxes.empty:
        df_camera_boxes = df_camera_boxes[[
            'timestamp', 'camera_timestamp', 'track_id', 'object_type', 
            'center_x', 'center_y', 'box_width', 'box_height',
            'rear_cx', 'rear_cy', 'front_cx', 'front_cy', 'rear_corners_2d', 'front_corners_2d', 'x_3d', 'y_3d', 'z_3d', 'yaw_3d', 'width_3d', 'length_3d'
        ]]
        
    return df_camera_boxes

def apply_bounding_box_padding(camera_dataframes_dict, padding_factor=0.10, img_w=1920, img_h=1080):
    """
    Expands the bounding boxes for all cameras in the dictionary by a given percentage.
    Strictly clamps the resulting coordinates to the image boundaries to prevent SAM3 errors.
    
    padding_factor: 0.10 means a 10% increase in width and length.
    """
    padded_dict = {}
    
    for cam_name, df in camera_dataframes_dict.items():
        if df.empty:
            padded_dict[cam_name] = df.copy()
            continue
            
        # Create a working copy to preserve your original math
        df_padded = df.copy()
        
        # 1. Stretch the dimensions by the padding factor
        new_width = df_padded['width'] * (1.0 + padding_factor)
        new_length = df_padded['length'] * (1.0 + padding_factor)
        
        # 2. Recalculate the outer boundaries pushing outward from the center (x, y)
        df_padded['x_min'] = df_padded['x'] - (new_width / 2.0)
        df_padded['y_min'] = df_padded['y'] - (new_length / 2.0)
        df_padded['x_max'] = df_padded['x'] + (new_width / 2.0)
        df_padded['y_max'] = df_padded['y'] + (new_length / 2.0)
        
        # 3. Strictly clamp the boundaries so they cannot fall off the image canvas
        df_padded['x_min'] = df_padded['x_min'].clip(lower=0).round().astype(int)
        df_padded['y_min'] = df_padded['y_min'].clip(lower=0).round().astype(int)
        df_padded['x_max'] = df_padded['x_max'].clip(upper=img_w).round().astype(int)
        df_padded['y_max'] = df_padded['y_max'].clip(upper=img_h).round().astype(int)
        
        # Update the visual width/length to match the new clamped box
        df_padded['width'] = df_padded['x_max'] - df_padded['x_min']
        df_padded['length'] = df_padded['y_max'] - df_padded['y_min']
        
        padded_dict[cam_name] = df_padded
        
    return padded_dict
